#include "main.h"           /* HAL 库基础，必须第一个 */
#include "bsp_adc.h"        /* 自己的头，拿到 ADC_CH_* 宏和函数原型 */
#include "adc.h"            /* hadc1 的 extern 声明在这里 —— 不包含就找不到 hadc1 */

/* ==================== DMA 落地缓冲 ==================== */
static volatile uint16_t s_adc_raw[ADC_CH_COUNT];
/*  ↑↑↑ 这个 volatile 是本文件最重要的一行 ↑↑↑
 *
 *  不加会怎样：编译器看到「s_adc_raw 在这个文件里从来没被赋值过」
 *    （确实没有赋值语句 —— 是 DMA 硬件改的，编译器看不见）
 *  于是它把「读 s_adc_raw[ch]」优化成「读一次，之后一直用这个缓存值」
 *  结果：主循环永远读到上电时的 0，屏幕上永远是 0.00V
 *
 *  加了 volatile：告诉编译器「这个变量可能被程序之外的东西改，
 *    每次用到都必须重新从内存读，不许缓存」
 *
 *  ⚠️ 这是嵌入式开发最经典的坑之一，一次踩坑能查一整天 */

/* ==================== 滑动平均缓冲 ==================== */
static uint16_t s_filt_buf[ADC_CH_COUNT][ADC_FILTER_N];
/*  ↑ 二维数组：[哪个通道][窗口内第几个]
 *    两个通道各自一份，互不干扰
 *    大小 = 2 × 8 × 2字节 = 32 字节，RAM 完全无压力 */

static uint8_t  s_filt_idx[ADC_CH_COUNT];
/*  ↑ 每个通道「下一个该写到哪个位置」
 *    范围 0~7，写满绕回 0 —— 这就是「环形」的含义 */

static uint8_t  s_filt_cnt[ADC_CH_COUNT];
/*  ↑ 每个通道「已经填了几个」
 *    范围 0~8，封顶在 8
 *    为什么要它：上电前几次窗口没填满，不能除以 8（见 2.1 节） */

/* ==================== 运行标志 ==================== */
static uint8_t  s_running = 0;
/*  ↑ 1 = DMA 启动成功。启动失败时置 0，Adc_IsRunning() 能查出来 */

/*---------------------------------------------------------------------------
 * 初始化：启动 ADC + DMA 循环搬运
 * 调用位置：main() 的 USER CODE BEGIN 2 区，MX_ADC1_Init() 之后
 *---------------------------------------------------------------------------*/
void Adc_Init(void)
{
    uint8_t ch, i;

    /* ---- 第一步：缓冲清零 ---- */
    for (ch = 0; ch < ADC_CH_COUNT; ch++) {
        s_filt_idx[ch] = 0;         /* 从 [0] 开始写 */
        s_filt_cnt[ch] = 0;         /* 还没填过 */
        for (i = 0; i < ADC_FILTER_N; i++) {
            s_filt_buf[ch][i] = 0;  /* 内容清零 */
        }
    }
    /*  为什么必须清：这是 static 变量，理论上启动文件会清零（BSS 段）
     *  但如果这个函数被调第二次（比如软复位后），旧数据还在
     *  显式清零 = 行为确定，不依赖启动文件做什么 */

    /* ---- 第二步：启动 ADC + DMA ---- */
    if (HAL_ADC_Start_DMA(&hadc1, (uint32_t *)s_adc_raw, ADC_CH_COUNT) != HAL_OK) {
        /*  ↑ 这一个函数把三件事全做了：
         *    ① 使能 ADC（ADON 置位）+ 启动第一次转换（SWSTART）
         *    ② 使能 DMA 请求（ADC->CR2 的 DMA 位）
         *    ③ 启动 DMA 流（DMA2_Stream0 的 EN 位）
         *  参数 2 = 缓冲区地址，DMA 往这里写
         *  参数 3 = 搬多少个数据，2 个（对应 Rank1、Rank2）
         *
         *  ⚠️ (uint32_t *) 这个强转看起来莫名其妙，讲清楚：
         *    HAL 的函数原型是 HAL_ADC_Start_DMA(ADC_HandleTypeDef*, uint32_t*, uint32_t)
         *    但实际搬运的数据宽度由 DMA 配置决定（这里配的是 HALFWORD 16 位）
         *    所以传 uint16_t 数组是对的，只是 HAL 的签名写成了 uint32_t*
         *    这是 HAL 库的历史遗留问题，官方例程也都这么强转
         *    不强转会报 warning: incompatible pointer types */
        s_running = 0;              /* 启动失败，记下来 */
        return;                     /* 直接返回，不要往下走 */
    }

    /* ---- 第三步：等 ADC 完成至少一轮转换 ---- */
    {
        uint32_t guard = 0;
        /*  ↑ 为什么要等：HAL_ADC_Start_DMA 返回时，ADC 才刚开始第一次转换
         *    此刻 s_adc_raw 里还是 0（或者上一轮的残留）
         *    主循环第一圈 Power_Task 读到 0 → s_volt = 0 → 0 < VOLT_MIN
         *    → Power_IsAbnormal() = 1 → 上电就误报欠压，还锁 5 秒
         *
         *    一轮转换 = 2 通道 × 4.57µs ≈ 9.14µs
         *    这里等电压通道出现非 0 值，正常几微秒就过
         *
         *  ⚠️ 为什么只判电压不判电流：电流可能是真的 0（空载）
         *     电压不太可能真的是 0（除非电源没接）
         *
         *  ⚠️ guard 上限是「兜底」：万一 PB1 根本没接信号（分压电路缺失），
         *     s_adc_raw 永远是 0，没有上限这里就死循环，整个系统卡在初始化
         *     10 万次空转 ≈ 1ms（168MHz），等不到就带病往下走，
         *     后面 Power_Task 会如实算出 0V 并报警 —— 那才是正确的报错方式 */
        while (s_adc_raw[ADC_CH_VOLT] == 0u && guard < 100000u) {
            guard++;
        }
    }

    s_running = 1;                  /* 成功 */
}

/*---------------------------------------------------------------------------
 * 取一次原始值（不做平均）
 * 参数 ch：ADC_CH_CURR(0) 或 ADC_CH_VOLT(1)
 *---------------------------------------------------------------------------*/
uint16_t Adc_GetRaw(uint8_t ch)
{
    if (ch >= ADC_CH_COUNT) {
        return 0u;
        /*  ↑ 越界保护。为什么要：s_adc_raw 只有 2 个元素
         *    传 ch=5 会读到数组后面的野内存
         *    C 语言不检查边界，编译器不报错，运行时照读
         *    和 15 篇里 App_State_GetThreshold 的越界保护同一个道理 */
    }
    return s_adc_raw[ch];
    /*  ↑ volatile 保证这次是「真的从内存读」，不是用寄存器里的缓存值 */
}

/*---------------------------------------------------------------------------
 * 取滑动平均后的值，返回 0~4095
 * 调用频率：主循环每圈调一次即可
 *---------------------------------------------------------------------------*/
uint16_t Adc_GetAvg(uint8_t ch)
{
    uint32_t sum = 0;               /* 累加用 32 位：8 × 4095 = 32760，超 uint16 上限 */
    uint8_t  i;
    uint8_t  n;

    if (ch >= ADC_CH_COUNT) {
        return 0u;                  /* 越界保护 */
    }

    /* ---- 第一步：把当前原始值塞进环形缓冲 ---- */
    s_filt_buf[ch][s_filt_idx[ch]] = s_adc_raw[ch];
    /*  ↑ 当前位置写入最新值，覆盖掉窗口里最老的那个 */

    s_filt_idx[ch]++;
    if (s_filt_idx[ch] >= ADC_FILTER_N) {
        s_filt_idx[ch] = 0;
        /*  ↑ 写到第 8 个之后绕回开头
         *    没有这行，s_filt_idx 会一直涨到 255 然后越界写内存 */
    }

    /* ---- 第二步：有效计数封顶 ---- */
    if (s_filt_cnt[ch] < ADC_FILTER_N) {
        s_filt_cnt[ch]++;
        /*  ↑ 前 7 次每次 +1：1,2,3,...,8
         *    第 9 次起已经等于 8，不再增加 —— 封顶 */
    }
    n = s_filt_cnt[ch];

    /* ---- 第三步：求和 ---- */
    for (i = 0; i < n; i++) {
        sum += s_filt_buf[ch][i];
        /*  ↑ 只加前 n 个。
         *    上电第一次 n=1，只加 [0]（刚写进去那个）—— 结果就是原值
         *    第 5 次 n=5，加 [0]~[4] —— 平均的是这 5 个真实值
         *    第 9 次起 n=8，加满窗口 */
    }

    return (uint16_t)(sum / n);
    /*  ↑ 除以「实际有效个数」而不是固定 8
     *    这就是为什么上电不会看到「电压从 0.6V 慢慢爬上来」 */
}

/*---------------------------------------------------------------------------
 * 查 DMA 是否已经跑起来
 *---------------------------------------------------------------------------*/
uint8_t Adc_IsRunning(void)
{
    return s_running;
}