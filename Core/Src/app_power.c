#include "main.h"           /* HAL 基础 */
#include "app_power.h"      /* 自己的头：ADC_VREF / VOLT_DIV_RATIO 等宏 */
#include "bsp_adc.h"        /* Adc_Init / Adc_GetAvg / ADC_CH_* */

/* ==================== 内部状态 ==================== */
static float   s_volt     = 0.0f;
/*  ↑ 最近一次算出的电压（V）
 *    初值 0 无所谓 —— 上电第一圈 Power_Task 就会算出真值 */

static float   s_curr_ma  = 0.0f;
/*  ↑ 最近一次算出的电流（mA） */

static uint8_t s_abnormal = 0;
/*  ↑ 1 = 越限，0 = 正常
 *    这是「即时判断」，不带锁存 —— 锁存在 app_state.c 里做（那里有 5 秒保持）*/

/*---------------------------------------------------------------------------
 * 初始化
 *---------------------------------------------------------------------------*/
void Power_Init(void)
{
    Adc_Init();             /* 启动 ADC + DMA，之后搬运全自动 */
    s_volt     = 0.0f;
    s_curr_ma  = 0.0f;
    s_abnormal = 0;
    /*  ↑ 数值归零。
     *    为什么 Adc_Init 里的清缓冲还不够：这里是「业务层初值」，
     *    万一 Power_Task 在第一次 Adc_GetAvg 之前就被别的函数读了，
     *    读到 0 比读到随机值安全 */
}

/*---------------------------------------------------------------------------
 * 周期任务：取平均 → 换算 → 判超限
 * 调用频率：主循环每圈一次
 *---------------------------------------------------------------------------*/
void Power_Task(void)
{
    uint16_t raw_volt;
    uint16_t raw_curr;
    float    v_pin;

    /* ---- 第一步：取滤波后的原始值 ---- */
    raw_volt = Adc_GetAvg(ADC_CH_VOLT);
    /*  ↑ 电压通道：下标 1，对应 PB1/CH9
     *    这一步同时做了「读最新值」和「塞进滑动窗口、算 8 次平均」 */

    raw_curr = Adc_GetAvg(ADC_CH_CURR);
    /*  ↑ 电流通道：下标 0，对应 PB0/CH8
     *    ⚠️ 顺序容易搞反！所以这里两个都用宏，不写 0/1 */

    /* ---- 第二步：换算电压 ---- */
    v_pin    = (float)raw_volt / ADC_FULL * ADC_VREF;
    /*  ↑ 三个要点：
     *    ① (float) 强转不能省 —— raw_volt 是 uint16_t，不转的话
     *       raw_volt / 4095.0f 会先…… 其实这里因为 4095.0f 是浮点，
     *       编译器会自动把 raw_volt 提升成 float，不转会也能算对
     *       但显式写更清楚，也避免以后改成整数除法时踩坑
     *    ② 乘法顺序：先除后乘，还是先乘后除？
     *       先除后乘：raw/4095 的结果是 0~1，精度够（float 有 24 位尾数）
     *       先乘后除：raw*3.3 最大 13513，也够
     *       两种都行，这里按「先归一化再缩放」的直觉写
     *    ③ 结果是引脚上的电压，范围 0~3.3V */

    s_volt   = v_pin * VOLT_DIV_RATIO;
    /*  ↑ 乘分压比，还原成「分压之前」的实际电压
     *    这一步全靠 VOLT_DIV_RATIO 正确，错了整个读数就废了 */

    /* ---- 第三步：换算电流 ---- */
    v_pin     = (float)raw_curr / ADC_FULL * ADC_VREF;
    /*  ↑ 复用 v_pin 这个临时变量（电压已经存进 s_volt 了，不用再占一个）*/

    s_curr_ma = v_pin * CURR_MA_PER_V;
    /*  ↑ 单位是 mA。
     *    如果 CURR_MA_PER_V = 1000（1V ↔ 1000mA），那么 0.5V → 500mA
     *    阈值 CURR_MAX_MA = 500 就是「引脚电压超过 0.5V 报警」 */

    /* ---- 第四步：判超限 ---- */
    if (s_volt < VOLT_MIN || s_volt > VOLT_MAX || s_curr_ma > CURR_MAX_MA) {
        /*  ↑ 条件用「或」（||）：任何一个越限都算异常
         *    - 电压太低（欠压）→ 异常
         *    - 电压太高（过压）→ 异常
         *    - 电流太高（过流）→ 异常
         *    - 电流太低不判（负载轻不是故障）
         *
         *    ⚠️ 和 15 篇里温湿度那个「进用 ||、退用 &&」不同：
         *       这里没有迟滞。为什么？
         *       电压电流的抖动量级远小于阈值余量（4.5/5.5 对 5.0V 额定），
         *       不会在边界上反复横跳，不需要迟滞
         *       如果实测发现跳动导致闪烁，再加迟滞 */
        s_abnormal = 1;
    } else {
        s_abnormal = 0;
    }
}

/*---------------------------------------------------------------------------
 * 读电压（V）
 *---------------------------------------------------------------------------*/
float Power_GetVoltage(void)
{
    return s_volt;
}

/*---------------------------------------------------------------------------
 * 读电流（mA）
 *---------------------------------------------------------------------------*/
float Power_GetCurrent(void)
{
    return s_curr_ma;
}

/*---------------------------------------------------------------------------
 * 是否越限
 *---------------------------------------------------------------------------*/
uint8_t Power_IsAbnormal(void)
{
    return s_abnormal;
}