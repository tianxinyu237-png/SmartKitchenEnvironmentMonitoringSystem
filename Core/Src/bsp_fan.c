#include "main.h"           /* HAL 库基础，必须第一个 */
#include "bsp_fan.h"        /* 自己的头，拿到 FAN_SPEED_* 宏和函数原型 */
#include "tim.h"            /* htim3 的 extern 声明在这里 —— 不包含就找不到 htim3 */

/* ==================== 内部定义 ==================== */
#define FAN_CHANNEL    TIM_CHANNEL_1
/*  ↑ 用宏而不是直接写 TIM_CHANNEL_1，将来换通道（比如 PC6 改 PC8 用 CH3）
 *    只改这一行。而且 CH1/CH2/CH3/CH4 对应的是不同引脚，写错就没输出 */

#define FAN_ARR        999u
/*  ↑ 必须和 tim.c 里 htim3.Init.Period = 999 保持一致
 *    只用于注释说明，代码里没直接用到（CCR 直接填千分比就行）
 *    但如果将来改了 ARR，这里也要改，否则占空比换算全错 */

/* ==================== 内部状态 ==================== */
static uint16_t s_speed = 0;
/*  ↑ 记一份当前档位
 *    为什么要记：__HAL_TIM_SET_COMPARE 是「写进去就完事」，读不回来
 *    （其实能读 CCR 寄存器，但没有「期望值」和「实际值」的区分，记一份更清晰）
 *    static = 文件私有 + 全程存活，和 app_state.c 里那些变量一样的道理 */

/*---------------------------------------------------------------------------
 * 初始化：启动 PWM，占空比归零
 * 什么时候调：main() 里 MX_TIM3_Init() 之后，只调一次
 *---------------------------------------------------------------------------*/
void Fan_Init(void)
{
    HAL_TIM_PWM_Start(&htim3, FAN_CHANNEL);
    /*  ↑ 这一句是「使能输出通道」，它做的事：
     *    ① 把 TIM3->CCER 寄存器的 CC1E 位置 1（Channel 1 Enable）
     *    ② 设置 CC1P 位（输出极性，这里是高有效）
     *    ③ 如果配置了互补输出还会开 CC1NE
     *    不调这句 → CCR 里填什么都不输出，PC6 一直是低电平
     *    ⚠️ 这是本工程最容易漏的一句 */

    __HAL_TIM_SET_COMPARE(&htim3, FAN_CHANNEL, 0u);
    /*  ↑ 上电先归零，别一开机就全速转
     *    注意顺序：先 Start 再设 0，还是先设 0 再 Start 都行
     *    但习惯上先 Start —— 因为 Start 之前设的值也会被保留 */

    s_speed = 0;
}

/*---------------------------------------------------------------------------
 * 设定转速
 * 参数 permille：0~1000 千分比。0 = 停，500 = 50%，1000 = 全速
 *---------------------------------------------------------------------------*/
void Fan_SetSpeed(uint16_t permille)
{
    if (permille > 1000u) {
        permille = 1000u;
        /*  ↑ 钳位。为什么要：如果调用方传了 5000（比如把百分数当千分数传），
         *    CCR 会写成 5000 > ARR(999) → 输出恒高 → 100% 全速
         *    虽然是「安全」的（不会损坏），但调用方以为自己在设 50%，
         *    实际是 100%，行为对不上。钳住更可控 */
    }

    __HAL_TIM_SET_COMPARE(&htim3, FAN_CHANNEL, permille);
    /*  ↑ 这一个宏就是「调速」的全部。
     *    它展开成：htim3.Instance->CCR1 = permille;
     *    写进去立即生效（不需要重启动定时器），下一个 PWM 周期就按新占空比输出
     *    整个过程几个时钟周期，不阻塞、不用等 */

    s_speed = permille;
    /*  ↑ 记下来，供 Fan_GetSpeed() 查询 */
}

/*---------------------------------------------------------------------------
 * 停转，等价于 Fan_SetSpeed(0)
 *---------------------------------------------------------------------------*/
void Fan_Off(void)
{
    Fan_SetSpeed(0u);
    /*  ↑ 为什么不直接写 __HAL_TIM_SET_COMPARE(..., 0)：
     *    那样 s_speed 不会更新，Fan_GetSpeed() 会返回旧值
     *    委托给 Fan_SetSpeed 保证「状态」和「寄存器」永远一致 */
}

/*---------------------------------------------------------------------------
 * 查当前转速，返回 0~1000
 *---------------------------------------------------------------------------*/
uint16_t Fan_GetSpeed(void)
{
    return s_speed;
}